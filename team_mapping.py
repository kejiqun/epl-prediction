def translate_team_name(name):
    """智能翻译球队名，如果找不到就返回原名"""
    if not isinstance(name, str):
        return name
    cleaned_name = name.replace(" and ", " & ").strip()
    return TEAM_MAPPING.get(cleaned_name, name)
